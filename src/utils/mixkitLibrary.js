export function getMixkitByCategory(category = "") {
  const cat = (category || "").toUpperCase();
  let filtered = [];
  if (cat.includes("KOZMİK") || cat.includes("UZAY") || cat.includes("GECE") || cat.includes("ŞEHİR")) {
    filtered = VERIFIED_MIXKIT_TRACKS.filter(t => t.genre === "Kozmik" || t.genre === "Ambient");
  } else if (cat.includes("MOTİVASYON") || cat.includes("GÜÇ") || cat.includes("SPOR")) {
    filtered = VERIFIED_MIXKIT_TRACKS.filter(t => t.genre === "Motivasyon");
  } else if (cat.includes("DOĞA") || cat.includes("SU") || cat.includes("HUZUR")) {
    filtered = VERIFIED_MIXKIT_TRACKS.filter(t => t.genre === "Chillout" || t.genre === "Ambient");
  } else {
    filtered = VERIFIED_MIXKIT_TRACKS.filter(t => t.genre === "Piyano" || t.genre === "Dramatik");
  }
  if (!filtered.length) filtered = VERIFIED_MIXKIT_TRACKS;
  return filtered[Math.floor(Math.random() * filtered.length)];
}
