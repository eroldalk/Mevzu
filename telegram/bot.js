import "dotenv/config";
import { Telegraf } from "telegraf";
import { requireAuthorization } from "./auth.js";
import { registerCommands } from "./commands.js";
import { startScheduler, stopScheduler } from "./scheduler.js";
if (!process.env.TELEGRAM_BOT_TOKEN) throw new Error("TELEGRAM_BOT_TOKEN tanımlı değil.");
const bot = new Telegraf(process.env.TELEGRAM_BOT_TOKEN);
bot.use(requireAuthorization);
registerCommands(bot);
bot.catch((error) => console.error("[Telegram] İşlenemeyen bot hatası:", error.message));
await bot.launch();
startScheduler(bot);
console.log("Telegram Mevzu görsel post yönetim botu başlatıldı.");
const shutdown = (signal) => { stopScheduler(); bot.stop(signal); };
process.once("SIGINT", () => shutdown("SIGINT"));
process.once("SIGTERM", () => shutdown("SIGTERM"));
